// Package local implements ports.Storage on the local filesystem. It is the C0
// adapter: one JSON file per order plus opaque blob files, both written atomically.
//
// Layout under the configured directory:
//
//	orders/<32-hex-id>.json
//	blobs/<32-hex-id or _system>/<kind>/<name>
//
// A single RWMutex guards the store. That is fine at prototype scale; per-key
// sharding is a later optimization, not a C0 concern.
package local

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"

	"github.com/artemidius/insteadly/internal/core/domain"
	"github.com/artemidius/insteadly/internal/core/ports"
)

// Store is the local-disk implementation of ports.Storage.
type Store struct {
	mu  sync.RWMutex
	dir string
}

// New creates the storage directories eagerly so an unwritable path fails at startup
// rather than on the first write.
func New(dir string) (*Store, error) {
	if strings.TrimSpace(dir) == "" {
		return nil, fmt.Errorf("local storage: dir is required")
	}
	for _, sub := range []string{"orders", "blobs"} {
		p := filepath.Join(dir, sub)
		if err := os.MkdirAll(p, 0o750); err != nil {
			return nil, fmt.Errorf("local storage: create %s: %w", p, err)
		}
	}
	return &Store{dir: dir}, nil
}

// Orders returns the order store (the Store itself).
func (s *Store) Orders() ports.OrderStore { return s }

// Blobs returns the blob store (the Store itself).
func (s *Store) Blobs() ports.BlobStore { return s }

var orderIDPattern = regexp.MustCompile(`^[0-9a-f]{32}$`)

// validOrderID reports whether id matches the 32-lowercase-hex form generated by
// domain.NewOrderID. Every ID that reaches a filesystem path must pass this check.
func validOrderID(id domain.OrderID) bool { return orderIDPattern.MatchString(string(id)) }

func (s *Store) orderPath(id domain.OrderID) (string, error) {
	if !validOrderID(id) {
		return "", fmt.Errorf("invalid order id %q", id)
	}
	return filepath.Join(s.dir, "orders", string(id)+".json"), nil
}

// writeAtomic writes a file via a same-directory temp file and rename: a crash can
// leave the temp file behind but never a half-written target. The rename is atomic on
// APFS and POSIX filesystems. The write callback streams into the temp file.
func writeAtomic(path string, perm os.FileMode, write func(io.Writer) error) (err error) {
	f, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return fmt.Errorf("create temp file: %w", err)
	}
	tmp := f.Name()
	committed := false
	defer func() {
		if !committed {
			_ = f.Close()
			_ = os.Remove(tmp)
		}
	}()

	if err := write(f); err != nil {
		return err
	}
	// CreateTemp already uses 0600; set it explicitly so the health-data guarantee
	// does not depend on the temp-file default.
	if err := f.Chmod(perm); err != nil {
		return fmt.Errorf("chmod temp file: %w", err)
	}
	if err := f.Sync(); err != nil {
		return fmt.Errorf("sync temp file: %w", err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("close temp file: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("rename temp file: %w", err)
	}
	committed = true
	return nil
}
